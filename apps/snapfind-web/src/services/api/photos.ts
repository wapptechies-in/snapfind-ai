import { mockProcessingJobs } from "../../data/mockProcessing";
import type { Photo, ProcessingJob } from "../../types";
import { API_BASE_URL, delay, downloadFile, getAuthToken, request } from "./client";

export interface UploadInitResult {
  photoId: string;
  uploadUrl: string;
  storageKey: string;
  headers: Record<string, string>;
  expiresIn: number;
}

export interface PhotoUrlResult {
  photoId: string;
  url: string;
  variant: string;
  expiresIn: number;
  filename: string;
}

/**
 * Local storage URLs are generated by the backend.  On a phone, a loopback
 * host (127.0.0.1 / localhost) refers to the phone rather than the server, so
 * resolve those URLs against the API host that delivered this gallery.
 */
function normalizePhotoUrl(url?: string): string | undefined {
  if (!url) return url;

  let cleanUrl = url.trim();

  // If root-relative path (e.g. /api/v1/storage/file/...)
  if (cleanUrl.startsWith("/")) {
    cleanUrl = `${API_BASE_URL}${cleanUrl}`;
  }

  try {
    const parsed = new URL(cleanUrl);
    if (
      parsed.hostname === "127.0.0.1" ||
      parsed.hostname === "localhost" ||
      parsed.hostname === "0.0.0.0"
    ) {
      return `${API_BASE_URL}${parsed.pathname}${parsed.search}${parsed.hash}`;
    }
  } catch {
    if (!cleanUrl.startsWith("http://") && !cleanUrl.startsWith("https://")) {
      return `${API_BASE_URL}/${cleanUrl.replace(/^\/+/, "")}`;
    }
  }

  // Force HTTPS on secure hosts to prevent Mixed Content browser blocking
  if (
    typeof window !== "undefined" &&
    window.location.protocol === "https:" &&
    cleanUrl.startsWith("http://") &&
    !cleanUrl.includes("localhost") &&
    !cleanUrl.includes("127.0.0.1") &&
    !cleanUrl.includes("0.0.0.0")
  ) {
    cleanUrl = cleanUrl.replace(/^http:\/\//i, "https://");
  }

  return cleanUrl;
}

function normalizePhotoUrls(photo: any): Photo {
  const rawThumb = photo.thumbnailUrl || photo.thumbnail_url || photo.url || photo.web_url;
  const rawWeb = photo.url || photo.web_url || photo.thumbnailUrl || photo.thumbnail_url;
  const thumb = normalizePhotoUrl(rawThumb);
  const web = normalizePhotoUrl(rawWeb);

  return {
    ...photo,
    url: web || thumb || "",
    thumbnailUrl: thumb || web || "",
  };
}

export const photosApi = {
  /**
   * Fetch all photos associated with an event.
   */
  async getByEventId(eventId: string): Promise<Photo[]> {
    try {
      const res = await request<{ items: Photo[]; total: number }>(
        `/api/v1/events/${eventId}/photos?limit=200`
      );
      if (res && res.items) {
        return res.items.map(normalizePhotoUrls);
      }
    } catch (err) {
      console.warn("Could not load photos from API:", err);
    }
    return [];
  },

  /**
   * Step 1: Initialize direct binary upload and obtain presigned PUT URL.
   */
  async uploadInit(
    eventId: string,
    payload: { filename: string; fileSize: number; mimeType: string; folderId?: string | null }
  ): Promise<UploadInitResult> {
    const res = await request<UploadInitResult>(`/api/v1/events/${eventId}/photos/upload-init`, {
      method: "POST",
      body: JSON.stringify(payload),
    });
    return {
      ...res,
      uploadUrl: normalizePhotoUrl(res.uploadUrl) || res.uploadUrl,
    };
  },

  /**
   * Step 2: Directly upload binary to MinIO/S3 using presigned PUT URL with progress tracking
   * and automatic backend proxy fallback if direct upload fails (e.g. CORS preflight restriction).
   */
  uploadBinary(
    uploadUrl: string,
    file: File,
    mimeType: string,
    onProgress?: (percent: number) => void,
    storageKey?: string
  ): Promise<void> {
    const cleanStorageKey = storageKey ? storageKey.replace(/^\/+/, "") : "";
    const backendFallbackUrl = cleanStorageKey
      ? `${API_BASE_URL}/api/v1/storage/upload?key=${encodeURIComponent(cleanStorageKey)}`
      : null;

    const normalizedTargetUrl = normalizePhotoUrl(uploadUrl) || uploadUrl;

    const executePut = (targetUrl: string): Promise<void> => {
      return new Promise((resolve, reject) => {
        const xhr = new XMLHttpRequest();
        xhr.open("PUT", targetUrl, true);
        xhr.setRequestHeader("Content-Type", mimeType || file.type || "image/jpeg");

        const token = getAuthToken();
        const isBackendUpload =
          targetUrl.includes("/storage/upload") ||
          targetUrl.includes("/api/v1/storage") ||
          targetUrl.includes("onrender.com");
        if (token && isBackendUpload) {
          xhr.setRequestHeader("Authorization", `Bearer ${token}`);
        }

        if (xhr.upload && onProgress) {
          xhr.upload.onprogress = (event) => {
            if (event.lengthComputable) {
              const percent = Math.round((event.loaded / event.total) * 100);
              onProgress(percent);
            }
          };
        }

        xhr.onload = () => {
          if (xhr.status >= 200 && xhr.status < 300) {
            resolve();
          } else {
            reject(new Error(`Storage PUT failed with status ${xhr.status}: ${xhr.statusText || "Upload rejected"}`));
          }
        };

        xhr.onerror = () => {
          reject(new Error(`Network error during PUT upload to ${targetUrl}`));
        };

        xhr.send(file);
      });
    };

    // First try direct storage PUT (or normalized URL)
    return executePut(normalizedTargetUrl).catch((primaryErr) => {
      console.warn("Direct storage upload failed, attempting backend fallback upload:", primaryErr);
      if (backendFallbackUrl && backendFallbackUrl !== normalizedTargetUrl) {
        return executePut(backendFallbackUrl).catch((fallbackErr) => {
          console.error("Backend fallback upload also failed:", fallbackErr);
          throw new Error("Network error during photo upload. Please check your connection and retry.");
        });
      }
      throw new Error("Network error during direct binary upload to storage. Check connection and retry.");
    });
  },

  /**
   * Step 3: Notify backend that upload finished, trigger derivative generation & AI indexing.
   */
  async uploadComplete(photoId: string): Promise<Photo> {
    return request<Photo>(`/api/v1/photos/${photoId}/upload-complete`, {
      method: "POST",
      body: JSON.stringify({ photoId }),
    });
  },

  /**
   * Generate short-lived presigned URL for viewing or downloading a photo.
   */
  async getPhotoUrl(
    photoId: string,
    variant: "original" | "web" | "thumbnail" = "web",
    download: boolean = false,
    downloadToken?: string
  ): Promise<PhotoUrlResult> {
    const params = new URLSearchParams({
      variant,
      download: String(download),
    });
    if (downloadToken) {
      params.set("downloadToken", downloadToken);
    }
    return request<PhotoUrlResult>(
      `/api/v1/photos/${photoId}/url?${params.toString()}`
    );
  },

  /**
   * Delete photo from storage and database.
   */
  async delete(photoId: string): Promise<{ ok: boolean; id: string }> {
    return request<{ ok: boolean; id: string }>(`/api/v1/photos/${photoId}`, {
      method: "DELETE",
    });
  },

  /**
   * Bulk delete multiple photos and their storage objects in one batch.
   */
  async bulkDelete(photoIds: string[]): Promise<{ ok: boolean; deleted_count: number; deleted_ids: string[] }> {
    return request<{ ok: boolean; deleted_count: number; deleted_ids: string[] }>(
      "/api/v1/photos/bulk-delete",
      {
        method: "POST",
        body: JSON.stringify({ photo_ids: photoIds }),
      }
    );
  },

  /**
   * Download a selection of photos packaged into a single ZIP archive.
   */
  async downloadZip(photoIds: string[], variant: "web" | "original" = "web"): Promise<void> {
    await downloadFile("/api/v1/photos/download-zip", "snapfind-photos.zip", {
      method: "POST",
      body: JSON.stringify({ photo_ids: photoIds, variant }),
    });
  },

  /**
   * Fetch live processing job status for an event from Celery/Redis backend.
   */
  async getProcessingJob(eventId: string): Promise<ProcessingJob> {
    try {
      const res = await request<ProcessingJob>(`/api/v1/events/${eventId}/processing`);
      if (res && typeof res.progressPercent === "number") {
        return res;
      }
    } catch (err) {
      console.warn("Could not load live processing status from API, falling back to mock fixtures:", err);
    }

    await delay(100);
    return (
      mockProcessingJobs[eventId] || {
        ...mockProcessingJobs.default,
        eventId,
      }
    );
  },

  /**
   * Start processing for all pending photos in an event.
   */
  async startProcessing(eventId: string): Promise<{ success: boolean; message: string; jobId?: string }> {
    return request<{ success: boolean; message: string; jobId?: string }>(
      `/api/v1/events/${eventId}/processing/start`,
      { method: "POST" }
    );
  },

  /**
   * Re-process all photos in an event from scratch.
   */
  async reprocessEvent(eventId: string): Promise<{ success: boolean; message: string; jobId?: string }> {
    return request<{ success: boolean; message: string; jobId?: string }>(
      `/api/v1/events/${eventId}/processing/reprocess`,
      { method: "POST" }
    );
  },

  /**
   * Retry failed photos in an event.
   */
  async retryFailedPhotos(eventId: string): Promise<{ success: boolean; message: string; jobId?: string }> {
    return request<{ success: boolean; message: string; jobId?: string }>(
      `/api/v1/events/${eventId}/processing/retry-failed`,
      { method: "POST" }
    );
  },

  /**
   * Clean and remove failed / phantom photos in an event.
   */
  async cleanFailedPhotos(eventId: string): Promise<{ ok: boolean; message: string; cleaned_count: number }> {
    return request<{ ok: boolean; message: string; cleaned_count: number }>(
      `/api/v1/events/${eventId}/processing/clean-failed`,
      { method: "DELETE" }
    );
  },

  /**
   * Cancel active processing jobs in an event.
   */
  async cancelProcessing(eventId: string): Promise<{ success: boolean; message: string }> {
    return request<{ success: boolean; message: string }>(
      `/api/v1/events/${eventId}/processing/cancel`,
      { method: "POST" }
    );
  },
};
